// term — the terminal emulator of the Code mode's terminal panel (docs/CODE-TERMINAL.md): an
// xterm-compatible VT parser and screen model, GUI-free. The program runs on a pseudo-terminal
// (src/platform/pty.h); the app area src/app/terminal shows the screen and turns keys into input.
//
//   cell.h       Color, Pen, Cell, Line — a grid position (a code point or a cluster, its width,
//                colours, attributes, hyperlink) and a line of them
//   charwidth.h  charWidth(): the columns a code point takes (wcwidth()'s: East Asian Wide and
//                Fullwidth 2, combining marks 0), tables generated by scripts/term-width-table.py
//   parser.h     Parser: bytes → print / execute / ESC / CSI / OSC actions (Williams' DEC state
//                machine; UTF-8 decoded in the ground state, split reads and invalid bytes handled)
//   screen.h     Screen: the main and the alternate screen, the main screen's scrollback, cursor,
//                scroll region, tab stops, modes, character sets, which rows changed
//   terminal.h   Terminal (QObject): Parser + Screen + what the sequences mean; replies to the
//                program's queries (reply()), bell, title (OSC 0/2), working directory (OSC 7),
//                hyperlinks (OSC 8); OSC 52 — the clipboard — ignored
//   keys.h       encodeKey / encodePaste / encodeText / encodeFocus / encodeMouse: the input the
//                program gets for a key (Qt's key codes, QtCore), a paste, a mouse event
//   screentext.h logicalLine(), findText(): rows joined where the text wrapped, mapped back to
//                cells — the scrollback's search
//   links.h      findLinks(), resolvePath(): URLs and file paths (path:line:column) in the output
//                that no OSC 8 marked
//
//   brulion::term::Terminal t(80, 24);
//   t.feed("\x1b[1;31mzażółć\x1b[0m gęślą jaźń\r\n");
//   t.screen().line(0).trimmedText();   // "zażółć gęślą jaźń"
