/**
 * Tiny DOM helpers for CodeMirror widgets (plain DOM, no React inside the editor content) and
 * the icons they use (Lucide shapes, ISC licence, same set as the design system's <Icon>).
 * Browser-only: call from `toDOM` / event handlers.
 */

type Child = Node | string | null | undefined | false;

/** Create an element: `h('span', { class: 'x', 'data-lp': 'chip' }, 'text', child)`. */
export function h<K extends keyof HTMLElementTagNameMap>(
  tag: K,
  attrs: Record<string, string | number | boolean | null | undefined> = {},
  ...children: Child[]
): HTMLElementTagNameMap[K] {
  const el = document.createElement(tag);
  for (const [k, v] of Object.entries(attrs)) {
    if (v === null || v === undefined || v === false) continue;
    el.setAttribute(k, v === true ? '' : String(v));
  }
  for (const c of children) {
    if (c === null || c === undefined || c === false) continue;
    el.append(typeof c === 'string' ? document.createTextNode(c) : c);
  }
  return el;
}

/** Hidden copy of the replaced source, so a line's textContent stays its Markdown. */
export function sourceSpan(raw: string): HTMLElement {
  const s = document.createElement('span');
  s.className = 'b-lp-src';
  s.textContent = raw;
  return s;
}

