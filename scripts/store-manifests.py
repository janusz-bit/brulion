#!/usr/bin/env python3
"""Store manifests of a Brulion release: Flathub, winget, AUR and Homebrew (packaging/STORES.md).

    scripts/store-manifests.py --version 0.32.0 --sums SHA256SUMS.txt [--out packaging]

Reads the release's SHA256SUMS.txt (a file of the GitHub release) and writes, under --out:

    flathub/io.github.januszbit.brulion.yml      Flatpak manifest: the source tarball, KDE runtime
    winget/manifests/j/janusz-bit/Brulion/<v>/   the four winget manifests (Windows setup.exe)
    aur/brulion-bin/PKGBUILD, .SRCINFO           Arch User Repository: the x86_64/aarch64 AppImage
    homebrew/brulion.rb                          Homebrew formula (Linux): built from the source tarball

Nothing is sent anywhere: the files are what the owner submits to each store (packaging/STORES.md).
Every file is written whole each run (the same input gives the same bytes). Python's standard
library only.
"""
from __future__ import annotations

import argparse
import pathlib
import re
import sys

REPO = "janusz-bit/brulion"
HOMEPAGE = "https://github.com/janusz-bit/brulion"
APP_ID = "io.github.januszbit.brulion"
SUMMARY = "Offline-first Markdown notes with an outliner, journals and reminders"
SUMMARY_PL = "Notatki w Markdown offline: konspekt, dziennik i przypomnienia"
DESCRIPTION = (
    "Brulion keeps your notes as plain Markdown files in a folder you choose. Write them as a block "
    "outliner with daily journals, link pages and blocks, plan with a calendar, tasks, reminders "
    "and alarms, and calculate right inside your notes. Sync through Syncthing or Nextcloud, "
    "optionally end-to-end encrypted."
)
DESCRIPTION_PL = (
    "Brulion trzyma notatki jako zwykłe pliki Markdown w wybranym folderze. Piszesz je w konspekcie "
    "z blokami i w dzienniku, łączysz strony i bloki, planujesz w kalendarzu, z zadaniami, "
    "przypomnieniami i alarmami, a obliczenia liczysz wprost w notatkach. Synchronizacja przez "
    "Syncthing albo Nextcloud, także zaszyfrowana end-to-end."
)
LICENSE = "AGPL-3.0-or-later"
# The Inno Setup AppId of packaging/windows/brulion.iss: the uninstall entry's key is "<AppId>_is1".
INNO_APP_ID = "{5E3B8C1A-7F42-4D6B-9A0E-2C8D4B6F1E37}"


def yaml_text(text: str) -> str:
    """A YAML scalar of free text: single-quoted (a colon or a hash inside stays text)."""
    return "'" + text.replace("'", "''") + "'"


def release_url(version: str, name: str) -> str:
    return f"https://github.com/{REPO}/releases/download/v{version}/{name}"


def parse_sums(text: str) -> dict[str, str]:
    """`sha256  name` lines (sha256sum's output) as {name: sha256}."""
    sums: dict[str, str] = {}
    for line in text.splitlines():
        m = re.fullmatch(r"([0-9a-f]{64})\s+\*?(\S+)", line.strip())
        if m:
            sums[m.group(2)] = m.group(1)
    return sums


def need(sums: dict[str, str], name: str) -> str:
    if name not in sums:
        sys.exit(f"store-manifests: {name} is not in the release's SHA256SUMS")
    return sums[name]


def flathub(version: str, sums: dict[str, str]) -> dict[str, str]:
    tarball = f"brulion-{version}-source.tar.gz"
    return {
        f"flathub/{APP_ID}.yml": f"""# Flathub manifest of Brulion {version} (generated by scripts/store-manifests.py; packaging/STORES.md).
# Built from the release's source tarball with the KDE runtime (Qt 6.12), without the model on the
# device (BRULION_LOCAL_AI) and without the update check (Flathub updates the app itself).
id: {APP_ID}
runtime: org.kde.Platform
runtime-version: '6.12'
sdk: org.kde.Sdk
command: brulion
finish-args:
  - --share=ipc
  - --share=network          # Nextcloud / WebDAV sync, calendars, AI providers the user sets up
  - --socket=wayland
  - --socket=fallback-x11
  - --device=dri
  - --filesystem=home        # the notebook is a folder of the user's files (Obsidian does the same)
  - --talk-name=org.freedesktop.Notifications  # reminders and alarms
  - --talk-name=org.kde.StatusNotifierWatcher  # the tray icon and its calendar
modules:
  - name: brulion
    buildsystem: cmake-ninja
    config-opts:
      - -DCMAKE_BUILD_TYPE=Release
      - -DBUILD_TESTING=OFF
      - -DBRULION_LOCAL_AI=OFF
      - -DBRULION_UPDATE_CHECK=OFF
    sources:
      - type: archive
        url: {release_url(version, tarball)}
        sha256: {need(sums, tarball)}
""",
    }


def winget(version: str, sums: dict[str, str]) -> dict[str, str]:
    setup = f"Brulion-{version}-windows-x86_64-setup.exe"
    base = f"winget/manifests/j/janusz-bit/Brulion/{version}"
    header = "# Generated by scripts/store-manifests.py (packaging/STORES.md).\n"
    pkg = "janusz-bit.Brulion"
    return {
        f"{base}/{pkg}.yaml": header + f"""# yaml-language-server: $schema=https://aka.ms/winget-manifest.version.1.6.0.schema.json
PackageIdentifier: {pkg}
PackageVersion: {version}
DefaultLocale: en-US
ManifestType: version
ManifestVersion: 1.6.0
""",
        f"{base}/{pkg}.installer.yaml": header + f"""# yaml-language-server: $schema=https://aka.ms/winget-manifest.installer.1.6.0.schema.json
PackageIdentifier: {pkg}
PackageVersion: {version}
InstallerType: inno
Scope: user
InstallModes:
  - interactive
  - silent
  - silentWithProgress
UpgradeBehavior: install
ProductCode: '{INNO_APP_ID}_is1'
Installers:
  - Architecture: x64
    InstallerUrl: {release_url(version, setup)}
    InstallerSha256: {need(sums, setup).upper()}
ManifestType: installer
ManifestVersion: 1.6.0
""",
        f"{base}/{pkg}.locale.en-US.yaml": header + f"""# yaml-language-server: $schema=https://aka.ms/winget-manifest.defaultLocale.1.6.0.schema.json
PackageIdentifier: {pkg}
PackageVersion: {version}
PackageLocale: en-US
Publisher: janusz-bit
PublisherUrl: https://github.com/janusz-bit
PackageName: Brulion
PackageUrl: {HOMEPAGE}
License: {LICENSE}
LicenseUrl: {HOMEPAGE}/blob/main/LICENSE
ShortDescription: {yaml_text(SUMMARY)}
Description: {yaml_text(DESCRIPTION)}
Moniker: brulion
Tags:
  - markdown
  - notes
  - outliner
  - journal
  - offline
ReleaseNotesUrl: {HOMEPAGE}/releases/tag/v{version}
ManifestType: defaultLocale
ManifestVersion: 1.6.0
""",
        f"{base}/{pkg}.locale.pl-PL.yaml": header + f"""# yaml-language-server: $schema=https://aka.ms/winget-manifest.locale.1.6.0.schema.json
PackageIdentifier: {pkg}
PackageVersion: {version}
PackageLocale: pl-PL
ShortDescription: {yaml_text(SUMMARY_PL)}
Description: {yaml_text(DESCRIPTION_PL)}
ManifestType: locale
ManifestVersion: 1.6.0
""",
    }


def aur(version: str, sums: dict[str, str]) -> dict[str, str]:
    x86 = f"Brulion-{version}-x86_64.AppImage"
    arm = f"Brulion-{version}-aarch64.AppImage"
    pkgbuild = f"""# Maintainer: janusz-bit
# Generated by scripts/store-manifests.py (packaging/STORES.md): Brulion's AppImage, unpacked.
pkgname=brulion-bin
pkgver={version}
pkgrel=1
pkgdesc="{SUMMARY}"
arch=('x86_64' 'aarch64')
url="{HOMEPAGE}"
license=('{LICENSE}')
depends=('fuse2' 'hicolor-icon-theme')
provides=('brulion')
conflicts=('brulion')
options=('!strip' '!debug')
source_x86_64=("{x86}::{release_url(version, x86)}")
source_aarch64=("{arm}::{release_url(version, arm)}")
sha256sums_x86_64=('{need(sums, x86)}')
sha256sums_aarch64=('{need(sums, arm)}')

prepare() {{
    chmod +x "Brulion-$pkgver-$CARCH.AppImage"
    "./Brulion-$pkgver-$CARCH.AppImage" --appimage-extract > /dev/null
}}

package() {{
    install -d "$pkgdir/opt/brulion" "$pkgdir/usr/bin"
    cp -a squashfs-root/. "$pkgdir/opt/brulion/"
    for program in brulion brulion-cli; do
        if [[ -e "squashfs-root/usr/bin/$program" ]]; then
            ln -s "/opt/brulion/usr/bin/$program" "$pkgdir/usr/bin/$program"
        fi
    done
    install -Dm644 "squashfs-root/{APP_ID}.desktop" "$pkgdir/usr/share/applications/{APP_ID}.desktop"
    sed -i 's|^Exec=.*|Exec=brulion %U|' "$pkgdir/usr/share/applications/{APP_ID}.desktop"
    for icon in squashfs-root/usr/share/icons/hicolor/*/apps/{APP_ID}.*; do
        install -Dm644 "$icon" "$pkgdir/${{icon#squashfs-root/}}"
    done
}}
"""
    srcinfo = f"""pkgbase = brulion-bin
\tpkgdesc = {SUMMARY}
\tpkgver = {version}
\tpkgrel = 1
\turl = {HOMEPAGE}
\tarch = x86_64
\tarch = aarch64
\tlicense = {LICENSE}
\tdepends = fuse2
\tdepends = hicolor-icon-theme
\tprovides = brulion
\tconflicts = brulion
\toptions = !strip
\toptions = !debug
\tsource_x86_64 = {x86}::{release_url(version, x86)}
\tsha256sums_x86_64 = {need(sums, x86)}
\tsource_aarch64 = {arm}::{release_url(version, arm)}
\tsha256sums_aarch64 = {need(sums, arm)}

pkgname = brulion-bin
"""
    return {"aur/brulion-bin/PKGBUILD": pkgbuild, "aur/brulion-bin/.SRCINFO": srcinfo}


def homebrew(version: str, sums: dict[str, str]) -> dict[str, str]:
    tarball = f"brulion-{version}-source.tar.gz"
    return {
        "homebrew/brulion.rb": f"""# Homebrew formula of Brulion {version} (generated by scripts/store-manifests.py; packaging/STORES.md).
# Linux only for now: Brulion has no macOS build yet (TODO.md "iOS, iPadOS and macOS").
class Brulion < Formula
  desc "{SUMMARY}"
  homepage "{HOMEPAGE}"
  url "{release_url(version, tarball)}"
  sha256 "{need(sums, tarball)}"
  license "{LICENSE}"

  depends_on "cmake" => :build
  depends_on "ninja" => :build
  depends_on "pkgconf" => :build
  depends_on "hunspell"
  depends_on :linux
  depends_on "qt" # 6.12 or later

  def install
    system "cmake", "-S", ".", "-B", "build", "-G", "Ninja",
           "-DBUILD_TESTING=OFF", "-DBRULION_LOCAL_AI=OFF", "-DBRULION_UPDATE_CHECK=OFF",
           *std_cmake_args
    system "cmake", "--build", "build"
    system "cmake", "--install", "build"
  end

  test do
    assert_match version.to_s, shell_output("#{{bin}}/brulion-cli --version")
  end
end
""",
    }


def manifests(version: str, sums: dict[str, str]) -> dict[str, str]:
    if not re.fullmatch(r"\d+\.\d+\.\d+", version):
        sys.exit(f"store-manifests: {version!r} is not a release version (x.y.z)")
    out: dict[str, str] = {}
    for part in (flathub, winget, aur, homebrew):
        out.update(part(version, sums))
    return out


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--version", required=True)
    ap.add_argument("--sums", required=True, type=pathlib.Path, help="the release's SHA256SUMS.txt")
    ap.add_argument("--out", type=pathlib.Path, default=pathlib.Path(__file__).resolve().parent.parent / "packaging")
    args = ap.parse_args()
    files = manifests(args.version, parse_sums(args.sums.read_text(encoding="utf-8")))
    for rel, text in files.items():
        path = args.out / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(f"store-manifests: {path}")


if __name__ == "__main__":
    main()
