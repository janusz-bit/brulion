#!/usr/bin/env python3
"""Regenerate src/core/term/charwidth_table_p.h: the terminal's column widths of code points.

The terminal emulator (src/core/term, docs/CODE-TERMINAL.md "Character widths") gives every code
point the width programs count with wcwidth(): two columns for East Asian Wide and Fullwidth
characters (emoji with an emoji presentation are Wide since Unicode 9) and for the CJK planes 2 and
3, none for combining marks (Mn, Me), format characters (Cf: ZERO WIDTH JOINER, the variation
selectors are Mn) and the Hangul medial vowels and final consonants U+1160-U+11FF, one for
everything else (SOFT HYPHEN U+00AD too). The tables come from Python's unicodedata, so the
Unicode version is the Python's:

    scripts/term-width-table.py            # writes src/core/term/charwidth_table_p.h
"""

import pathlib
import unicodedata


def ranges(predicate):
    out = []
    start = None
    for cp in range(0x110000):
        if predicate(cp):
            if start is None:
                start = cp
        elif start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def wide(cp):
    if 0x20000 <= cp <= 0x2FFFD or 0x30000 <= cp <= 0x3FFFD:
        return True
    return unicodedata.east_asian_width(chr(cp)) in ("W", "F")


def zero(cp):
    if 0x1160 <= cp <= 0x11FF:
        return True
    if cp == 0x00AD:
        return False
    return unicodedata.category(chr(cp)) in ("Mn", "Me", "Cf")


def table(name, items):
    lines = [f"inline constexpr CodeRange {name}[] = {{"]
    row = []
    for a, b in items:
        row.append(f"{{0x{a:04X}, 0x{b:04X}}},")
        if len(row) == 4:
            lines.append("    " + " ".join(row))
            row = []
    if row:
        lines.append("    " + " ".join(row))
    lines.append("};")
    return "\n".join(lines)


def main():
    root = pathlib.Path(__file__).resolve().parent.parent
    out = root / "src/core/term/charwidth_table_p.h"
    text = f"""// Generated by scripts/term-width-table.py from Unicode {unicodedata.unidata_version} (Python's
// unicodedata) — do not edit. The ranges of code points two columns wide (East Asian Wide and
// Fullwidth, the CJK planes 2 and 3) and of those without a width of their own (Mn, Me, Cf, Hangul
// U+1160-U+11FF), sorted, for charwidth.cpp's binary search.
#pragma once

namespace brulion::term::detail {{

struct CodeRange {{
    char32_t first;
    char32_t last;
}};

// clang-format off
{table("WideRanges", ranges(wide))}

{table("ZeroWidthRanges", ranges(zero))}
// clang-format on

}} // namespace brulion::term::detail
"""
    out.write_text(text, encoding="utf-8")
    print(f"wrote {out.relative_to(root)}")


if __name__ == "__main__":
    main()
