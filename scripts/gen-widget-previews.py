#!/usr/bin/env python3
# Generates the Android widget picker's preview images for Android 9-11 (android:previewImage in
# android/res/xml/widget_*_info.xml; Android 12+ show previewLayout) as vector drawables whose
# colours follow day/night, plus optional SVG twins in the light colours to look at:
#
#   scripts/gen-widget-previews.py android/res/drawable [svg-dir]
#   (rsvg-convert svg-dir/tasks.svg -o tasks.png)
import sys, os
out_res = sys.argv[1]
out_svg = sys.argv[2] if len(sys.argv) > 2 else None
LIGHT = {"widget_background": "#FBF7EE", "widget_surface": "#F1EBDD", "widget_text": "#1F2430",
         "widget_muted": "#6B6556", "widget_faint": "#A39A87", "widget_accent": "#2C6AA3",
         "widget_overdue": "#C8473B", "widget_reminder": "#B7791F", "widget_scheduled": "#6E8B3D",
         "widget_button": "#1F2430", "widget_button_text": "#FBF7EE", "widget_border": "#E4DCCB"}

def rrect(x, y, w, h, r):
    return (f"M{x+r},{y} H{x+w-r} A{r},{r} 0 0 1 {x+w},{y+r} V{y+h-r} A{r},{r} 0 0 1 {x+w-r},{y+h} "
            f"H{x+r} A{r},{r} 0 0 1 {x},{y+h-r} V{y+r} A{r},{r} 0 0 1 {x+r},{y} Z")

def circle(cx, cy, r):
    return f"M{cx-r},{cy} A{r},{r} 0 1 0 {cx+r},{cy} A{r},{r} 0 1 0 {cx-r},{cy} Z"

class Img:
    def __init__(self, w, h):
        self.w, self.h, self.items = w, h, []
    def fill(self, d, color):
        self.items.append(("fill", d, color, 0))
    def line(self, x1, y1, x2, y2, color, width):
        self.items.append(("stroke", f"M{x1},{y1} L{x2},{y2}", color, width))
    def stroke(self, d, color, width):
        self.items.append(("stroke", d, color, width))
    def xml(self, comment):
        lines = ['<?xml version="1.0" encoding="utf-8"?>', f"<!-- {comment} Generated by scripts/gen-widget-previews.py; the colours follow day/night. -->",
                 '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
                 f'    android:width="{self.w}dp"', f'    android:height="{self.h}dp"',
                 f'    android:viewportWidth="{self.w}"', f'    android:viewportHeight="{self.h}">']
        for kind, d, color, width in self.items:
            if kind == "fill":
                lines.append(f'    <path android:fillColor="@color/{color}" android:pathData="{d}" />')
            else:
                lines.append(f'    <path android:strokeColor="@color/{color}" android:strokeWidth="{width}" '
                             f'android:strokeLineCap="round" android:pathData="{d}" />')
        lines.append("</vector>")
        return "\n".join(lines) + "\n"
    def svg(self):
        parts = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{self.w*3}" height="{self.h*3}" viewBox="0 0 {self.w} {self.h}">',
                 f'<rect width="{self.w}" height="{self.h}" fill="#333"/>']
        for kind, d, color, width in self.items:
            if kind == "fill":
                parts.append(f'<path fill="{LIGHT[color]}" d="{d}"/>')
            else:
                parts.append(f'<path fill="none" stroke="{LIGHT[color]}" stroke-width="{width}" stroke-linecap="round" d="{d}"/>')
        parts.append("</svg>")
        return "\n".join(parts)

def plus_button(img, cx, cy):
    img.fill(circle(cx, cy, 11), "widget_button")
    img.line(cx - 5, cy, cx + 5, cy, "widget_button_text", 2)
    img.line(cx, cy - 5, cx, cy + 5, "widget_button_text", 2)

def task_row(img, y, length, color="widget_text"):
    img.stroke(circle(20, y, 3.5), "widget_faint", 1.5)
    img.line(30, y, 30 + length, y, color, 4)

# Tasks, 3x2: "Mój dzień", the date, +, Zaległe with one task, Dziś with two.
t = Img(180, 110)
t.fill(rrect(0, 0, 180, 110, 16), "widget_background")
t.line(16, 18, 74, 18, "widget_text", 7)
t.line(16, 31, 96, 31, "widget_muted", 4)
plus_button(t, 158, 22)
t.line(16, 49, 44, 49, "widget_overdue", 3.5)
task_row(t, 60, 96)
t.line(16, 75, 36, 75, "widget_accent", 3.5)
task_row(t, 86, 84)
t.line(124, 86, 146, 86, "widget_reminder", 4)
task_row(t, 98, 80)

# Calendar, 4x4: month, ‹ ›, weekdays, the grid with today and coloured dots, then the agenda.
c = Img(250, 250)
c.fill(rrect(0, 0, 250, 250, 16), "widget_background")
c.line(16, 20, 92, 20, "widget_text", 7)
c.stroke("M196,14 L190,20 L196,26", "widget_muted", 2)
c.stroke("M226,14 L232,20 L226,26", "widget_muted", 2)
x0, colw = 16, (250 - 32) / 7
for i in range(7):
    cx = x0 + colw * (i + 0.5)
    c.line(cx - 4, 40, cx + 4, 40, "widget_faint", 3)
dots = {(1, 2): ["widget_overdue"], (2, 1): ["widget_accent", "widget_reminder"], (2, 4): ["widget_scheduled"],
        (3, 0): ["widget_accent"], (3, 5): ["widget_reminder"], (4, 3): ["widget_accent", "widget_scheduled", "widget_reminder"]}
today = (2, 1)
for row in range(6):
    cy = 56 + row * 21
    for col in range(7):
        cx = x0 + colw * (col + 0.5)
        if (row, col) == today:
            c.fill(circle(cx, cy, 9), "widget_accent")
            c.line(cx - 3.5, cy, cx + 3.5, cy, "widget_button_text", 3.5)
        else:
            c.line(cx - 3.5, cy, cx + 3.5, cy, "widget_text" if 0 < row * 7 + col - 2 < 33 else "widget_faint", 3.5)
        for k, color in enumerate(dots.get((row, col), [])):
            n = len(dots[(row, col)])
            c.fill(circle(cx + (k - (n - 1) / 2) * 5, cy + 11, 1.8), color)
c.line(16, 190, 230, 190, "widget_border", 1)
c.line(16, 204, 70, 204, "widget_muted", 3.5)
c.line(16, 218, 36, 218, "widget_reminder", 4)
c.line(44, 218, 150, 218, "widget_text", 4)
c.line(16, 232, 36, 232, "widget_accent", 4)
c.line(44, 232, 128, 232, "widget_text", 4)

# Notes, 3x2: title, "Dziennik dziś" and "Szybka notatka" pills, favourites.
n = Img(180, 110)
n.fill(rrect(0, 0, 180, 110, 16), "widget_background")
n.line(16, 18, 66, 18, "widget_text", 7)
n.line(16, 31, 90, 31, "widget_muted", 4)
plus_button(n, 158, 22)
n.fill(rrect(14, 42, 72, 20, 10), "widget_surface")
n.line(26, 52, 74, 52, "widget_text", 4)
n.fill(rrect(94, 42, 72, 20, 10), "widget_surface")
n.line(106, 52, 154, 52, "widget_text", 4)
n.line(16, 74, 46, 74, "widget_muted", 3.5)
for i, length in enumerate([70, 98]):
    y = 86 + i * 13
    n.fill(rrect(16, y - 4.5, 7, 9, 1.5), "widget_faint")
    n.line(30, y, 30 + length, y, "widget_text", 4)

if out_svg:
    os.makedirs(out_svg, exist_ok=True)
for name, img, what in [("tasks", t, "Tasks widget"), ("calendar", c, "Calendar widget"), ("notes", n, "Notes widget")]:
    with open(os.path.join(out_res, f"widget_preview_{name}_image.xml"), "w") as f:
        f.write(img.xml(f"The widget picker's preview of the {what} before Android 12 (android:previewImage; 12+ show previewLayout)."))
    if out_svg:
        with open(os.path.join(out_svg, f"{name}.svg"), "w") as f:
            f.write(img.svg())
