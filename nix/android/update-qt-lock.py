"""Writes nix/android/qt-android.json: the Qt for Android archives (one per Qt module and ABI)
that nix/android/qt.nix fetches, with their SHA-256 hashes.

The archives come from Qt's online repository (the one aqt and the Qt online installer use):
  <repo>/all_os/android/qt6_<v>/qt6_<v>_<abi>/Updates.xml    lists the package
    qt.qt6.<v>.android_<abi> with its version and its archives (one .7z per Qt module),
  <repo>/.../qt.qt6.<v>.android_<abi>/<version><archive>      is an archive, and
  <repo>/.../<version><archive>.sha256                        its SHA-256, published by Qt.
Nothing is downloaded but the small Updates.xml and .sha256 files.

Usage: update-qt-lock.py QT_VERSION OUTPUT.json [--modules "qtbase qtdeclarative qtsvg"]
"""

import argparse
import base64
import json
import sys
import urllib.request
import xml.etree.ElementTree as ET

REPO = "https://download.qt.io/online/qtsdkrepository"

# Android ABI -> (directory suffix in the repository, Qt's arch name)
ABIS = {
    "arm64-v8a": ("arm64_v8a", "android_arm64_v8a"),
    "armeabi-v7a": ("armv7", "android_armv7"),
    "x86_64": ("x86_64", "android_x86_64"),
    "x86": ("x86", "android_x86"),
}


def fetch(url: str) -> bytes:
    request = urllib.request.Request(url, headers={"User-Agent": "brulion-update-qt-lock"})
    with urllib.request.urlopen(request, timeout=60) as response:
        return response.read()


def sri(hex_digest: str) -> str:
    return "sha256-" + base64.b64encode(bytes.fromhex(hex_digest)).decode()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("version", help="Qt version, e.g. 6.11.2 (the nixpkgs qt6.qtbase version)")
    parser.add_argument("output", help="the JSON lock to write")
    parser.add_argument("--modules", default="qtbase qtdeclarative qtsvg",
                        help="Qt modules to fetch (space separated; default: %(default)s). Only modules "
                             "of the main package (qtbase, qtdeclarative, qtsvg, qttools, qttranslations…); "
                             "add-ons such as qtimageformats or qtmultimedia are separate packages and not "
                             "supported yet")
    parser.add_argument("--abis", default=" ".join(ABIS), help="ABIs (default: %(default)s)")
    args = parser.parse_args()

    compact = args.version.replace(".", "")  # 6.11.2 -> 6112
    modules = args.modules.split()
    lock = {
        "!comment": "Generated by nix/android/update-locks.sh (update-qt-lock.py) - do not edit by hand.",
        "version": args.version,
        "modules": modules,
        "abis": {},
    }
    for abi in args.abis.split():
        repo_abi, qt_arch = ABIS[abi]
        base = f"all_os/android/qt6_{compact}/qt6_{compact}_{repo_abi}"
        package_name = f"qt.qt6.{compact}.{qt_arch}"
        updates = ET.fromstring(fetch(f"{REPO}/{base}/Updates.xml"))
        package = next((p for p in updates.iter("PackageUpdate") if p.findtext("Name") == package_name), None)
        if package is None:
            sys.exit(f"{package_name} is not in {REPO}/{base}/Updates.xml")
        package_version = package.findtext("Version")
        archives = [a.strip() for a in (package.findtext("DownloadableArchives") or "").split(",") if a.strip()]
        entries = {}
        for module in modules:
            # Archive names look like "qtbase-Linux-RHEL_9_6-Clang-Android-Android_ANY-X86_64.7z".
            matches = [a for a in archives if a.split("-", 1)[0] == module]
            if len(matches) != 1:
                sys.exit(f"{package_name}: expected one archive of {module}, found {matches} in {archives}"
                         " (add-on modules are separate packages, not supported yet)")
            path = f"{base}/{package_name}/{package_version}{matches[0]}"
            hex_digest = fetch(f"{REPO}/{path}.sha256").decode().split()[0]
            if len(hex_digest) != 64:
                sys.exit(f"unexpected checksum file for {path}: {hex_digest!r}")
            entries[module] = {"path": path, "hash": sri(hex_digest)}
            print(f"  {abi:12} {module:15} {matches[0]}", file=sys.stderr)
        lock["abis"][abi] = {"qtArch": qt_arch, "packageVersion": package_version, "archives": entries}

    with open(args.output, "w", encoding="utf-8") as out:
        json.dump(lock, out, indent=2)
        out.write("\n")
    print(f"wrote {args.output} (Qt {args.version}, {', '.join(lock['abis'])})", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
